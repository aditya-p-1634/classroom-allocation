"""Pydantic Schemas for Validation and Allocation Results.

Governed by Document 02 §2.2, Document 03 §10, and Document 05 Phase P5 authorization.
Encapsulates validation findings, constraint categories, severity levels, and truthful result statuses.
"""

from enum import Enum
from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field


class ConstraintCategory(str, Enum):
    """Documented hard constraint categories."""
    ROOM_TIME_EXCLUSIVITY = "room_time_exclusivity"
    COHORT_TIME_EXCLUSIVITY = "cohort_time_exclusivity"
    ROOM_CAPABILITY = "room_capability"
    AVAILABILITY = "availability"
    CAPACITY = "capacity"


class FindingStatus(str, Enum):
    """Validation finding status values."""
    PASS = "pass"
    FAIL = "fail"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"


class ValidationSeverity(str, Enum):
    """Severity classification of validation findings."""
    INFO = "info"
    WARNING = "warning"
    ERROR = "error"


class ValidationFinding(BaseModel):
    """Individual constraint check finding."""
    constraint: ConstraintCategory = Field(..., description="Target hard constraint")
    status: FindingStatus = Field(..., description="pass, fail, or insufficient_evidence")
    severity: ValidationSeverity = Field(..., description="info, warning, or error")
    session_id: Optional[str] = Field(None, description="Affected session identifier")
    room_id: Optional[str] = Field(None, description="Affected room identifier")
    academic_cycle: Optional[str] = Field(None, description="odd or even")
    day: Optional[str] = Field(None, description="Weekday")
    period: Optional[int] = Field(None, description="Period number")
    message: str = Field(..., description="Detailed diagnostic description")
    evidence: Dict[str, Any] = Field(default_factory=dict, description="Supporting data facts")


class AllocationStatus(str, Enum):
    """Truthful outcome status taxonomy per Document 02 §2.2 & Document 03 §10."""
    VALID_COMPLETE = "valid_complete"
    VALID_PARTIAL = "valid_partial"
    INVALID = "invalid_candidate"
    INFEASIBLE = "proven_infeasible"
    TIMEOUT = "timeout_uncertain"
    FAILED = "execution_failure"


class ValidationSummary(BaseModel):
    """Comprehensive validation outcome for a candidate allocation."""
    status: AllocationStatus = Field(..., description="Truthful result status classification")
    is_valid: bool = Field(..., description="True if candidate has 0 hard-constraint failures")
    is_complete: bool = Field(..., description="True if 100% of candidate sessions are assigned")
    total_sessions_checked: int = Field(0, description="Total sessions evaluated")
    assigned_sessions_count: int = Field(0, description="Total assigned sessions evaluated")
    unassigned_sessions_count: int = Field(0, description="Total sessions left unassigned")
    pass_count: int = Field(0, description="Number of passing constraint checks")
    fail_count: int = Field(0, description="Number of failing constraint checks")
    insufficient_evidence_count: int = Field(0, description="Number of unconfirmed checks")
    findings: List[ValidationFinding] = Field(default_factory=list, description="All individual findings")
    evidence_limitations: List[str] = Field(
        default_factory=list,
        description="Explicit caveats regarding missing or unverified factual data",
    )

    @property
    def error_findings(self) -> List[ValidationFinding]:
        """Returns only the failing (error) findings."""
        return [f for f in self.findings if f.status == FindingStatus.FAIL]


class AllocationCandidate(BaseModel):
    """Represents a proposed room allocation generated by an allocator or source timetable."""
    academic_cycle: str = Field("all", description="'odd', 'even', or 'all'")
    assignments: Dict[str, str] = Field(
        default_factory=dict,
        description="Mapping of session_id to assigned room_id",
    )
    unassigned_sessions: Dict[str, str] = Field(
        default_factory=dict,
        description="Mapping of session_id to explicit unassigned reason",
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Run metadata, allocator name, configuration parameters",
    )


class AllocationResult(BaseModel):
    """End-to-end result linking an allocation candidate to its independent validation."""
    candidate: AllocationCandidate
    validation: ValidationSummary
    allocator_name: str
    capacity_mode: str
    execution_time_ms: float
